/** Dimensionality of the OpenAI text-embedding-3-small model. */
export const EMBEDDING_DIMENSIONS = 1536;

/**
 * Q&A primitive: distinguishes a help-seeking "question" from a regular
 * "discussion" post. Only questions expose the solved/accepted-answer surface.
 */
export const postKindEnum = pgEnum("post_kind", ["discussion", "question"]);

export const posts = pgTable("posts", {
  id: uuid("id").defaultRandom().primaryKey(),
  authorId: text("author_id").notNull(),
  content: jsonb("content").$type<PostContentDto>().notNull(),
  kind: postKindEnum("kind").default("discussion").notNull(),
  /** 1536-dimension vector embedding generated by OpenAI text-embedding-3-small. */
  embedding: vector("embedding", { dimensions: EMBEDDING_DIMENSIONS }),
  contentHash: text("content_hash"),
  hidden: boolean("hidden").default(false).notNull(),
  /**
   * Q&A primitive: the comment the asker accepted as the answer. Plain uuid
   * (no FK) to avoid a posts↔comments cycle; cleared by the comments service
   * when the accepted comment is deleted.
   */
  acceptedCommentId: uuid("accepted_comment_id"),
  /** Q&A primitive: set when a question is marked solved (an answer accepted). */
  solvedAt: timestamp("solved_at", { withTimezone: true }),
  createdAt: timestamp("created_at", { withTimezone: true })
    .defaultNow()
    .notNull(),
  updatedAt: timestamp("updated_at", { withTimezone: true })
    .defaultNow()
    .notNull(),
});

export type Post = typeof posts.$inferSelect;
export type NewPost = typeof posts.$inferInsert;

