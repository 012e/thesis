/**
 * Central moderation record for a post. Each moderation event
 * (duplicate detection, harmful content, user report, admin flag)
 * creates a separate row here.
 */
export const postModeration = pgTable("post_moderation", {
  id: uuid("id").defaultRandom().primaryKey(),
  postId: uuid("post_id")
    .notNull()
    .references(() => posts.id, { onDelete: "cascade" }),
  /** Which pipeline step or action created this record. */
  source: moderationSourceEnum("source").notNull(),
  /** Current status of this moderation record. */
  status: moderationStatusEnum("status").default("pending").notNull(),
  /** Priority level — 'critical' instantly hides the post. */
  priority: flagPriorityEnum("priority").default("medium").notNull(),
  /** LLM confidence score (1-100), null if no LLM step ran. */
  llmConfidence: text("llm_confidence"),
  /** LLM-generated summary of why the post was flagged. */
  llmSummary: text("llm_summary"),
  /** ID of the most similar post (for duplicate detection). */
  similarPostId: uuid("similar_post_id"),
  /** Cosine similarity score (for duplicate detection). */
  similarityScore: text("similarity_score"),
  /** Raw moderation result from OpenAI (for harmful content). */
  moderationResult: jsonb("moderation_result"),
  /** Admin who reviewed, or null if not yet reviewed. */
  reviewedBy: text("reviewed_by"),
  /** When the record was reviewed. */
  reviewedAt: timestamp("reviewed_at", { withTimezone: true }),
  /** Admin's review note. */
  reviewNote: text("review_note"),
  createdAt: timestamp("created_at", { withTimezone: true })
    .defaultNow()
    .notNull(),
  updatedAt: timestamp("updated_at", { withTimezone: true })
    .defaultNow()
    .notNull(),
});

export type PostModeration = typeof postModeration.$inferSelect;
export type NewPostModeration = typeof postModeration.$inferInsert;

